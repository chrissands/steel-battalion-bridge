/*
 * sbdriver.exe - Steel Battalion Bridge driver helper (run elevated, normally by the installer).
 *
 *   sbdriver install <folder>   Generate a WinUSB INF for USB\VID_0A7B&PID_D000, sign it with a
 *                               machine-local certificate (private key destroyed immediately),
 *                               add it to the driver store and bind any connected controller.
 *   sbdriver uninstall          Remove the driver package, the device binding and the certificate.
 *   sbdriver status             Print whether the controller is present and which driver it uses.
 *
 * The driver itself is Microsoft's inbox WinUSB.sys - no custom kernel code is installed.
 * Certificate/catalog code is libwdi's pki.c (Pete Batard, LGPL-3.0), the same mechanism Zadig uses.
 *
 * Exit codes: 0 = success, 1 = failure, 2 = success but reboot required.
 */
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <setupapi.h>
#include <newdev.h>
#include <cfgmgr32.h>
#include <stdio.h>
#include <string.h>

BOOL CreateCat(LPCSTR szCatPath, LPCSTR szHWID, LPCSTR szSearchDir, LPCSTR* szFileList, DWORD cFileList);
BOOL SelfSignFile(LPCSTR szFileName, LPCSTR szCertSubject);
BOOL RemoveCertFromStore(LPCSTR szCertSubject, LPCSTR szStoreName);

#define HWID        "USB\\VID_0A7B&PID_D000"
#define INF_NAME    "steel_battalion_winusb.inf"
#define CAT_NAME    "steel_battalion_winusb.cat"
#define CERT_NAME   "CN=Steel Battalion Bridge WinUSB (local signing - private key deleted)"
#define REG_KEY     "SOFTWARE\\SteelBattalionBridge"

